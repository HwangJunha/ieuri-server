-- 빈 메시지 제약을 내려놓는다(SPEC-0021 R4).
--
-- V60이 이 제약을 `body_encrypted <> '' OR photo_object_key IS NOT NULL`로 좁혀 두었는데,
-- **그 조건에 걸리는 행이 바로 R4가 "삭제하지 않고 남긴다"고 정한 행이다** — 피드 인용만
-- 있던 과거 메시지는 인용이 사라져 본문도 사진도 없는 상태로 남는다.
--
-- 도메인은 이들을 복원할 수 있도록 Message.restore에서 빈 본문을 허용한다(AC4.1). 저장소가
-- 같은 행을 거부하면 두 결정이 서로 모순이고, 그런 행이 하나라도 있는 환경에서는 V60이
-- 중간에 실패한다(보존 테이블은 이미 만들어진 뒤다).
--
-- 빈 메시지 금지는 **생성 시점의 불변식이며 Message.create가 소유한다**(AC4.3). 저장소 제약은
-- 과거 데이터와 양립해야 하므로 여기서 없앤다.
--
-- V60을 고치지 않고 새 파일로 두는 이유는 **이미 적용되었기 때문이다.** Flyway는 파일 전체를
-- 해싱하므로 주석 한 줄만 바꿔도 체크섬이 깨져 기동이 막힌다.
