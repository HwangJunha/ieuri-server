-- 시군구 정적 테이블과 KTO 빅데이터 4종의 적재 구조(SPEC-0015 §1).
--
-- **데이터 행은 없다 — DDL만이다.** 시군구 경계 원본(행정구역 경계 GeoJSON)이 아직 확보되지
-- 않아 252행 적재는 원본이 들어온 뒤 별도 마이그레이션에서 한다. 그때 이 파일을 고치는 것이
-- 아니라 새 V 파일을 추가한다(적용된 마이그레이션은 불변이다).
--
-- **CREATE EXTENSION postgis는 여기 없다.** 확장 활성화는 CNPG 오퍼레이터가 소유한다(V15 참조).
--
-- 좌표는 (경도 위도) 순서다 — WKT · ST_MakePoint 모두 그렇다. 뒤집으면 한국이 지구 반대편으로
-- 가는데 위경도 범위가 겹쳐 에러 없이 조용히 틀린다(V15 참조).

CREATE TABLE sigungu
(
    -- 행정표준코드 5자리('11110' 형태). 행정안전부가 부여한 식별자라 대리키를 두지 않는다 —
    -- KTO 응답의 시군구 코드와 그대로 대조해야 하고, 클라이언트도 이 값으로 조인한다.
    -- 선행 0이 있어 숫자 타입으로 두면 '01110'이 1110이 되어 대조가 깨진다.
    code              varchar(5) PRIMARY KEY,

    -- 상위 시도 코드 2자리('11' 형태). code의 앞 2자리와 같으나 별도 컬럼으로 둔다 —
    -- substring 질의는 인덱스를 타지 못한다.
    province_code     varchar(2)   NOT NULL,

    -- 4개 언어 시군구명. 별도 테이블로 정규화하지 않는다 — 언어가 4개로 고정이고 252건뿐이라
    -- 정규화 이득이 없고 조회마다 조인이 붙는다(V43과 같은 판단).
    --
    -- ko·en은 원본이 항상 주므로 NOT NULL이다. ja·zh는 우리가 작성한 번역이라 nullable이다:
    -- 번역 없이 먼저 들어올 수 있고, 그때 폴백(활성 언어 → EN → KO)이 동작해야 한다.
    -- 빈 칸을 EN으로 미리 채우면 실제 번역이 들어왔는지 구분할 수 없다.
    name_ko           varchar(128) NOT NULL,
    name_en           varchar(128) NOT NULL,
    name_ja           varchar(128),
    name_zh           varchar(128),

    -- 시도명도 이 테이블의 컬럼이다(§1.4). 시도 레벨 데이터 테이블을 두지 않는다 — 시도와
    -- 시군구는 합산 불가라 두 레벨을 함께 두면 어느 쪽을 쓸지가 질의마다 갈린다. 계약의
    -- provinceName은 이름만 필요하므로 컬럼으로 충분하다.
    -- 252행에 시도명이 중복되지만, 정규화하면 조회마다 조인이 붙고 이득이 없다.
    province_name_ko  varchar(128) NOT NULL,
    province_name_en  varchar(128) NOT NULL,
    province_name_ja  varchar(128),
    province_name_zh  varchar(128),

    -- 시군구 경계.
    --
    -- **Polygon이 아니라 MultiPolygon이다.** 섬을 포함하는 시군구가 있어 단일 폴리곤으로
    -- 표현되지 않는다(옹진군 · 신안군 등). congestion_area(V43)가 Polygon으로 충분했던 것은
    -- 서울 시내 구역이라 그랬을 뿐이다. Polygon으로 두면 해당 시군구 적재가 타입 오류로 막힌다.
    --
    -- spot.location · congestion_area.boundary와 같은 geography를 쓴다 — 섞어 쓸 때 캐스팅이
    -- 필요 없다.
    --
    -- **JPA가 표현할 수 없는 타입이라 엔티티에 매핑하지 않는다.** 매핑하면 ddl-auto:validate가
    -- 기동 시 실패한다. 이 컬럼을 건드리는 질의는 전부 생 SQL 어댑터에 있다.
    boundary          geography(MultiPolygon, 4326) NOT NULL,

    -- 지도 카메라가 향할 대표 좌표. 경계가 사실상 정적이고 결과도 불변이라 질의 때마다
    -- 계산하지 않고 적재 시 한 번 계산해 넣는다(§1.2).
    --
    -- **적재하는 쪽에 대한 경고 — 산출식은 다음이며 다른 식으로 채우면 안 된다.**
    --   1) boundary의 폴리곤 중 면적이 가장 큰 조각을 고른다
    --   2) 그 조각 위에서 ST_PointOnSurface를 구한다
    --
    -- MultiPolygon에 ST_PointOnSurface를 통째로 적용하면 가장 큰 조각 위의 점이 나온다는
    -- 보장이 없다 — 옹진군의 대표 좌표가 작은 섬 하나에 찍힐 수 있다.
    --
    -- **ST_Centroid를 쓰지 않는다.** 오목한 도형에서 도형 밖으로 나가며, 그러면 카메라가 다른
    -- 시군구를 비춘다. ST_PointOnSurface는 내부 점을 보장한다(spec §7.1 · R3).
    center            geography(Point, 4326)        NOT NULL
);

COMMENT ON TABLE sigungu IS '시군구 252건의 정적 메타데이터(코드 · 4개 언어 명칭 · 경계 · 대표 좌표). KTO 지표 값은 담지 않는다.';

-- spot을 시군구로 묶는 공간 조인(§4)이 전체 스캔 없이 동작하기 위한 공간 인덱스.
-- ST_Within · ST_Intersects가 이 인덱스를 탄다.
CREATE INDEX idx_sigungu_boundary ON sigungu USING GIST (boundary);


-- ---------------------------------------------------------------------------
-- KTO 빅데이터 4종
--
-- **네 테이블 모두 sigungu_code에 FK를 걸지 않는다.** 같은 도메인이라 FK가 허용되는
-- 상황이지만 R9가 이를 뒤집는다: 알 수 없는 시군구 코드는 건너뛰고 계속해야 하는데, FK가
-- 있으면 그 행이 제약 위반으로 배치를 통째로 실패시킨다. KTO가 코드를 추가하면 우리 정적
-- 테이블이 먼저 갱신되어야 하고, 그 사이 정상 데이터까지 못 쌓이게 된다. 코드 유효성은
-- 애플리케이션 계층에서 확인하고 건너뛴 건수를 로그로 남긴다(§2.2).
--
-- **자연키마다 UNIQUE가 있다.** INSERT ... ON CONFLICT upsert가 이 제약을 대상으로 걸리며,
-- R7(멱등성)이 이것으로 성립한다. 제약을 지우면 재실행이 조용히 행을 중복시킨다.
--
-- **월 단위 지표의 기준월은 char(6)이 아니라 date다** — 해당 월 1일로 정규화해 넣는다.
-- 일 단위 테이블의 기준일과 타입이 같아져 최신 행 조회 · 기간 필터가 같은 형태로 쓰이고,
-- 문자열 비교에 기대지 않아도 된다. 적재 시 '202601' → DATE '2026-01-01'로 변환한다.
-- ---------------------------------------------------------------------------

-- 1) 방문자수 — 일 단위, 자연키 (시군구 코드, 기준일, 관광객 구분)
CREATE TABLE kto_visitor_count
(
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    sigungu_code  varchar(5)  NOT NULL,
    base_date     date        NOT NULL,

    -- 현지인 · 외국인 등 관광객 구분. CHECK을 걸지 않는다 — KTO가 구분을 늘리면 적재가
    -- 막히는데, 새 값이 들어와도 기능이 깨지지 않는다(V43 category와 같은 판단).
    visitor_type  varchar(32) NOT NULL,

    -- **integer가 아니라 NUMERIC이다.** 업스트림이 소수 문자열을 준다("176473.5"). 정수
    -- 컬럼에 넣으면 반올림으로 값이 조용히 바뀐다(R4).
    tou_num       numeric     NOT NULL,

    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT uk_kto_visitor_count_natural UNIQUE (sigungu_code, base_date, visitor_type)
);

COMMENT ON TABLE kto_visitor_count IS 'KTO 시군구 일별 방문자수. sigungu.code를 참조하지만 FK는 없다(R9 — 알 수 없는 코드를 건너뛰기 위함).';

-- 시군구별 최신 행 조회(추천 질의)가 인덱스만으로 끝나기 위한 정렬 인덱스.
CREATE INDEX idx_kto_visitor_count_latest ON kto_visitor_count (sigungu_code, base_date DESC);


-- 2) 집중률 — 일 단위(예측 대상일), 자연키 (시군구 코드, 관광지명, 대상일)
CREATE TABLE kto_concentration_rate
(
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    sigungu_code  varchar(5)   NOT NULL,

    -- **이 API만 관광지명이 자연키에 들어간다.** 시군구 안의 개별 관광지 단위로 값이 오기
    -- 때문이다. 따라서 이 테이블의 행 하나는 시군구 점수가 아니며, 시군구 점수로 쓰려면
    -- 집계가 필요하다(§3.2 — 평균인지 최댓값인지는 미결).
    --
    -- 관광지명으로 spot과 매칭하지 않는다 — 응답에 시군구 코드가 있어 이름을 볼 이유가 없다.
    tourist_spot_name varchar(256) NOT NULL,

    -- 예측 대상일. 관측일이 아니라 예측이 향하는 날짜다.
    target_date   date         NOT NULL,

    cnctr_rate    numeric      NOT NULL,

    created_at    timestamptz  NOT NULL DEFAULT now(),
    updated_at    timestamptz  NOT NULL DEFAULT now(),

    CONSTRAINT uk_kto_concentration_rate_natural UNIQUE (sigungu_code, tourist_spot_name, target_date)
);

COMMENT ON TABLE kto_concentration_rate IS 'KTO 관광지별 일간 집중률 예측. 시군구가 아니라 관광지 단위 값이라 지역 점수로 쓰려면 집계가 필요하다. FK 없음(R9).';

CREATE INDEX idx_kto_concentration_rate_latest ON kto_concentration_rate (sigungu_code, target_date DESC);


-- 3) 체류 강도 — 월 단위, 자연키 (시군구 코드, 기준월, 지표 코드)
CREATE TABLE kto_stay_intensity
(
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    sigungu_code  varchar(5)  NOT NULL,

    -- 해당 월 1일로 정규화한 기준월(위 주석 참조).
    base_month    date        NOT NULL,

    -- 지표 코드. 한 시군구·한 달에 여러 지표가 오므로 자연키에 포함된다.
    indicator_cd  varchar(32) NOT NULL,

    indicator_value numeric   NOT NULL,

    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT uk_kto_stay_intensity_natural UNIQUE (sigungu_code, base_month, indicator_cd)
);

COMMENT ON TABLE kto_stay_intensity IS 'KTO 시군구 월별 체류 강도. base_month는 해당 월 1일로 정규화한 date. FK 없음(R9).';

CREATE INDEX idx_kto_stay_intensity_latest ON kto_stay_intensity (sigungu_code, base_month DESC);


-- 4) 소비 강도 — 월 단위, 자연키 (시군구 코드, 기준월, 지표 코드)
CREATE TABLE kto_spending_intensity
(
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    sigungu_code  varchar(5)  NOT NULL,
    base_month    date        NOT NULL,
    indicator_cd  varchar(32) NOT NULL,
    indicator_value numeric   NOT NULL,

    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT uk_kto_spending_intensity_natural UNIQUE (sigungu_code, base_month, indicator_cd)
);

COMMENT ON TABLE kto_spending_intensity IS 'KTO 시군구 월별 소비 강도. base_month는 해당 월 1일로 정규화한 date. FK 없음(R9).';

CREATE INDEX idx_kto_spending_intensity_latest ON kto_spending_intensity (sigungu_code, base_month DESC);
