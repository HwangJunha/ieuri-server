-- 검색 노드 베이스라인. 이전 V1~V11을 하나로 접은 것이며, 접기 시점의 개발 검색 노드
-- 스키마(2026-08-23, ieuri-db/ieuri-search)를 pg_dump --schema-only로 옮겼다.
--
-- 메인과 **별도 Flyway 인스턴스**다(SearchDataSourceConfig.searchFlyway, locations=db/search-node).
-- 접은 이유와 개발 DB 처리는 메인 V1의 머리말과 같다.
--
-- **이 노드는 읽기 전용이다.** spot 계열이 논리 복제로 들어오므로 앱이 쓰면 복제와
-- 충돌한다. 여기 있는 테이블은 복제가 채울 그릇이고, 이 파일이 만드는 것은 그릇과
-- BM25 인덱스뿐이다.
--
-- ── 메인과 다른 점은 어긋난 것이 아니다 ─────────────────────────────────────
--
-- **이름과 타입은 메인과 일치해야 하지만, 제약은 구독자가 더 느슨해야 한다.**
-- NOT NULL·CHECK를 발행자와 똑같이 걸면 **컬럼이 추가되기 전 시점의 행이 복제로 올 때
-- 거부되어 복제가 막힌다.** 값의 정합성은 발행자가 이미 보장하므로 구독자는 그릇 역할만
-- 한다. (선례: `spot_reaction.spot_id`로 복제가 3.5GB 밀린 채 멈췄다.)
--
-- 그래서 지금 이런 차이가 **의도적으로** 남아 있다:
--   - `spot_catalog_translation.category` — 메인은 NOT NULL, 여기는 nullable.
--
-- **이 차이를 드리프트로 보고 조이지 말 것.** 복제가 멈춰도 앱은 정상으로 보이고
-- 검색 결과만 조용히 낡아간다 — 가장 늦게 발견되는 종류의 고장이다. 반대로 새 컬럼을
-- 더할 때는 DEFAULT를 두어 옛 행이 와도 값이 채워지게 한다(`visible`이 그 예다).
--
-- 옮기면서 걷어낸 것:
--   - `\restrict`/`\unrestrict`와 `SET` 프리앰블 — psql 전용이라 JDBC가 실행할 수 없다.
--   - `public.flyway_schema_history` — Flyway가 스스로 만든다. 여기서 만들면 첫 적용이
--     "이미 있다"로 깨진다.
--   - `CREATE SUBSCRIPTION search_sub` — 접속 문자열에 호스트와 passfile 경로가 박혀 있어
--     환경마다 다르다. 클러스터 구축 절차가 소유한다.
--   - `CREATE EXTENSION`(postgis·vector·pg_search)과 `paradedb` 스키마 — 확장 활성화는
--     CNPG 오퍼레이터가 슈퍼유저로 수행하며(매니페스트 values-search.yaml의
--     `database.extensions`, **순서까지 그쪽이 정한다** — vector가 pg_search보다 먼저여야
--     한다), 앱 롤 `ieuri`에는 그 권한이 없다. 넣으면 첫 배포가 그 줄에서
--     `permission denied to create extension`으로 멈춘다(실측 2026-08-23).
--     `paradedb`는 pg_search 설치가 함께 만드는 스키마라 여기서 만들 것이 아니다.
--
-- 확장이 없으면 이 파일은 bm25 인덱스 줄에서 실패한다 — 접기 전 V2가 적어 둔 대로
-- **의도된 fail-fast**다.

