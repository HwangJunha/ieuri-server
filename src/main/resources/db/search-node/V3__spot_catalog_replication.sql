-- SPEC-0019 · 검색 노드가 카탈로그를 받는다.
--
-- **이 경로는 검색 노드(ieuri-search) 전용이다.** 메인 DB는 db/migration이 소유한다.
--
-- 논리 복제는 행만 옮기고 테이블 구조는 옮기지 않는다. 구독자에 그릇이 미리 있어야 발행자의
-- 행을 받을 수 있어서 여기서 만든다.
--
-- **이름과 타입은 메인과 일치해야 한다** — 어긋나면 복제가 조용히 멈추고, 앱은 정상으로
-- 보이는데 검색 결과만 낡아간다(V1 헤더의 경고).
--
-- **제약은 반대다 — 구독자가 더 느슨해야 한다.** NOT NULL·CHECK를 발행자와 똑같이 걸면,
-- 컬럼 추가 이전 시점의 행이 복제로 올 때 거부되어 복제가 막힌다. 값의 정합성은 발행자가
-- 이미 보장하므로 구독자는 그릇 역할만 한다.
--
-- **선행 조건**: `ieuri-manifest`의 CNPG Publication에 `spot_catalog`·
-- `spot_catalog_translation`·`spot_catalog_festival`을 추가해야 한다. 현재 발행 대상은
-- spot·spot_festival·spot_reaction 셋뿐이다.

-- **이 파일은 재적용에 견뎌야 한다.** 이전 버전이 일부만 적용된 검색 노드가 실재하므로
-- (구조 재설계로 이 파일을 다시 썼다) 모든 DDL이 `IF EXISTS`/`IF NOT EXISTS`를 쓴다.
-- 없으면 부분 적용된 노드에서 "이미 존재한다"로 막히고, 그 지점부터 손으로 풀어야 한다.

-- ── spot.catalog_id (메인 V52와 동일: BIGINT, nullable, DEFAULT 없음) ──────
--
-- **FK를 걸지 않는다.** 복제는 부모·자식 순서를 보장하지 않아, FK가 있으면 카탈로그 행이
-- 아직 도착하지 않은 spot 행이 거부되어 복제가 멈춘다.
ALTER TABLE spot ADD COLUMN IF NOT EXISTS catalog_id BIGINT;

-- ── spot_catalog ───────────────────────────────────────────────────────────
--
-- 검색이 카드 값(좌표·썸네일·분류)을 여기서 가져온다.
--
-- **트리거를 두지 않는다** — location 값이 복제로 그대로 넘어오므로 두면 같은 값을 두 번 쓴다.
-- **CHECK 제약도 두지 않는다** — 구독자 제약이 발행자보다 엄격하면 복제가 막힌다. 값의
-- 정합성은 발행자가 이미 보장한다.
CREATE TABLE IF NOT EXISTS spot_catalog (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    map_x DOUBLE PRECISION NOT NULL,
    map_y DOUBLE PRECISION NOT NULL,
    location GEOGRAPHY(POINT, 4326) NOT NULL,
    thumbnail_image_url VARCHAR(500) NOT NULL,
    category VARCHAR(30) NOT NULL,
    copyright VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_spot_catalog_location ON spot_catalog USING GIST (location);
CREATE INDEX IF NOT EXISTS idx_spot_catalog_category ON spot_catalog (category);

-- ── spot_catalog_translation ───────────────────────────────────────────────
--
-- **검색의 본체다.** BM25 인덱스가 이 테이블에 걸리며(V4), pg_search가 평면 질의를 요구해
-- spot_catalog와 조인할 수 없다 — 그래서 좌표 사본이 여기에 있다.
--
-- FK를 걸지 않는 이유는 위와 같다(복제 순서 보장 없음).
CREATE TABLE IF NOT EXISTS spot_catalog_translation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    catalog_id BIGINT NOT NULL,
    language VARCHAR(2) NOT NULL,
    title VARCHAR(255) NOT NULL,
    address VARCHAR(500),
    map_x DOUBLE PRECISION NOT NULL,
    map_y DOUBLE PRECISION NOT NULL,
    location GEOGRAPHY(POINT, 4326) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    -- UNIQUE는 복제 충돌을 일으키지 않는다 — 발행자가 같은 제약을 갖고 있어 위반 행이
    -- 애초에 오지 않는다. 검색이 (catalog_id, language)로 조회하므로 인덱스로도 쓰인다.
    CONSTRAINT uq_spot_catalog_translation UNIQUE (catalog_id, language)
);

CREATE INDEX IF NOT EXISTS idx_spot_catalog_translation_catalog ON spot_catalog_translation (catalog_id);
CREATE INDEX IF NOT EXISTS idx_spot_catalog_translation_language ON spot_catalog_translation (language);

-- ── spot_catalog_festival ──────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS spot_catalog_festival (
    catalog_id BIGINT PRIMARY KEY,
    event_start_date DATE NOT NULL,
    event_end_date DATE NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_spot_catalog_festival_end_date ON spot_catalog_festival (event_end_date);

-- ── spot_reaction ──────────────────────────────────────────────────────────
--
-- 발행자가 `spot_id`를 지우고 `catalog_id`로 바꿨다(메인 V53). **구독자도 같은 모양이어야
-- 한다** — 구독자에만 남은 `spot_id NOT NULL`은 발행자가 보내지 않는 컬럼이라 복제가 멈춘다.
ALTER TABLE spot_reaction DROP CONSTRAINT IF EXISTS uq_spot_reaction;
ALTER TABLE spot_reaction DROP CONSTRAINT IF EXISTS fk_spot_reaction_spot;
DROP INDEX IF EXISTS idx_spot_reaction_spot_id;
DROP INDEX IF EXISTS idx_spot_reaction_spot_reaction;
DROP INDEX IF EXISTS idx_spot_reaction_liked_list;
ALTER TABLE spot_reaction DROP COLUMN IF EXISTS spot_id;

-- 남은 행은 방금 참조 축을 잃었다. 복제가 발행자의 행을 다시 채우므로 구독자에서 지워도
-- 잃는 것이 없다 — 이 DELETE가 없으면 행이 있는 노드에서 아래 NOT NULL 추가가 막힌다.
DELETE FROM spot_reaction;

ALTER TABLE spot_reaction ADD COLUMN IF NOT EXISTS catalog_id BIGINT NOT NULL;

ALTER TABLE spot_reaction DROP CONSTRAINT IF EXISTS uq_spot_reaction;
ALTER TABLE spot_reaction ADD CONSTRAINT uq_spot_reaction UNIQUE (member_id, catalog_id);

CREATE INDEX IF NOT EXISTS idx_spot_reaction_catalog_id ON spot_reaction (catalog_id);
CREATE INDEX IF NOT EXISTS idx_spot_reaction_catalog_reaction ON spot_reaction (catalog_id, reaction);
CREATE INDEX IF NOT EXISTS idx_spot_reaction_liked_list
    ON spot_reaction (member_id, reaction, updated_at DESC, catalog_id DESC);
