-- SPEC-0019 · 검색 노드가 카탈로그를 받는다.
--
-- **이 경로는 검색 노드(ieuri-search) 전용이다.** 메인 DB는 db/migration이 소유한다.
--
-- 논리 복제는 행만 옮기고 테이블 구조는 옮기지 않는다. 구독자에 그릇이 미리 있어야 발행자의
-- 행을 받을 수 있어서 여기서 만든다.
--
-- **컬럼 정의는 메인과 문자 단위로 일치해야 한다** — 어긋나면 복제가 조용히 멈추고, 앱은
-- 정상으로 보이는데 검색 결과만 낡아간다(V1 헤더의 경고).
--
-- **선행 조건**: `ieuri-manifest`의 CNPG Publication에 `spot_catalog`·
-- `spot_catalog_translation`·`spot_catalog_festival`을 추가해야 한다. 현재 발행 대상은
-- spot·spot_festival·spot_reaction 셋뿐이다.

-- ── spot.catalog_id (메인 V52와 동일: BIGINT, nullable, DEFAULT 없음) ──────
--
-- **FK를 걸지 않는다.** 복제는 부모·자식 순서를 보장하지 않아, FK가 있으면 카탈로그 행이
-- 아직 도착하지 않은 spot 행이 거부되어 복제가 멈춘다.
ALTER TABLE spot ADD COLUMN catalog_id BIGINT;

-- ── spot_catalog ───────────────────────────────────────────────────────────
--
-- 검색이 카드 값(좌표·썸네일·분류)을 여기서 가져온다. 제약은 메인과 같게 두되 **트리거는
-- 두지 않는다** — location 값이 복제로 그대로 넘어오므로 두면 같은 값을 두 번 쓴다.
CREATE TABLE spot_catalog (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    representative_name_ko VARCHAR(255) NOT NULL,
    name_source VARCHAR(20) NOT NULL,
    name_key VARCHAR(255),
    map_x DOUBLE PRECISION,
    map_y DOUBLE PRECISION,
    location geography(Point, 4326),
    thumbnail_image_url VARCHAR(500),
    category VARCHAR(30),
    copyright VARCHAR(20),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_spot_catalog_name_source CHECK (name_source IN ('OFFICIAL', 'DERIVED')),
    CONSTRAINT ck_spot_catalog_map_x CHECK (map_x IS NULL OR map_x BETWEEN -180 AND 180),
    CONSTRAINT ck_spot_catalog_map_y CHECK (map_y IS NULL OR map_y BETWEEN -90 AND 90)
);

-- 반경 필터·거리 정렬(popularSpots·ongoingFestivals·searchSpots).
CREATE INDEX idx_spot_catalog_location ON spot_catalog USING GIST (location);
CREATE INDEX idx_spot_catalog_category ON spot_catalog (category);

-- ── spot_catalog_translation ───────────────────────────────────────────────
--
-- **BM25 인덱스가 이 테이블에 걸린다**(V4). pg_search가 평면 질의를 요구해 조인을 받지
-- 못하므로, 검색이 이 테이블 단독으로 돌 수 있어야 한다.
--
-- **좌표가 여기 있는 이유가 그것이다**(메인 V55). 거리 필터·정렬이 BM25와 같은 질의 레벨에
-- 있어야 하는데 좌표는 `spot_catalog`에 있다 — 조인하면 인덱스 푸시다운이 깨진다. 그래서
-- 카탈로그의 좌표를 번역 행에 복사해 둔다. **트리거는 두지 않는다** — location 값이 복제로
-- 그대로 넘어오므로 두면 같은 값을 두 번 쓴다.
CREATE TABLE spot_catalog_translation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    catalog_id BIGINT NOT NULL,
    language VARCHAR(2) NOT NULL,
    title VARCHAR(255) NOT NULL,
    address VARCHAR(500),
    source VARCHAR(20) NOT NULL,
    map_x DOUBLE PRECISION,
    map_y DOUBLE PRECISION,
    location geography(Point, 4326),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_spot_catalog_translation UNIQUE (catalog_id, language),
    CONSTRAINT ck_spot_catalog_translation_language CHECK (language IN ('EN', 'KO', 'JA', 'ZH')),
    CONSTRAINT ck_spot_catalog_translation_source CHECK (source IN ('OFFICIAL', 'MACHINE'))
);

CREATE INDEX idx_spot_catalog_translation_language ON spot_catalog_translation (language, catalog_id);

-- 검색의 거리 필터·정렬(searchSpots·suggestSpots).
CREATE INDEX idx_spot_catalog_translation_location
    ON spot_catalog_translation USING GIST (location);

-- ── spot_catalog_festival ──────────────────────────────────────────────────
--
-- 진행 중 축제 조회(`ongoingFestivals`)가 이 노드에서 돌므로 기간도 여기 있어야 한다.
--
-- **기간은 언어와 무관한 장소 자체의 속성이라 카탈로그 단위다**(메인 V52). 그래서 이 조회는
-- 더 이상 `spot`·`spot_festival`을 보지 않는다 — `spot_festival`은 원본 보관용으로 남는다.
--
-- **FK를 걸지 않는다.** 복제는 부모·자식 순서를 보장하지 않아, 카탈로그 행이 아직 도착하지
-- 않은 축제 행이 거부되어 복제가 멈춘다(위 spot.catalog_id와 같은 판단).
CREATE TABLE spot_catalog_festival (
    catalog_id BIGINT PRIMARY KEY,
    event_start_date DATE NOT NULL,
    event_end_date DATE NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_spot_catalog_festival_period CHECK (event_end_date >= event_start_date)
);

-- 종료일로 거르는 조회가 타는 인덱스.
CREATE INDEX idx_spot_catalog_festival_end_date ON spot_catalog_festival (event_end_date);

-- ── spot_reaction.catalog_id ───────────────────────────────────────────────
--
-- 인기 spot 집계가 카탈로그 단위로 바뀐다. **NOT NULL로 조이지 않는다** — 구독자 쪽 제약이
-- 발행자보다 엄격하면 중간 상태의 행이 거부되어 복제가 멈춘다.
ALTER TABLE spot_reaction ADD COLUMN catalog_id BIGINT;
CREATE INDEX idx_spot_reaction_catalog_reaction ON spot_reaction (catalog_id, reaction);

-- **옛 축을 반드시 걷어내야 한다.** 메인 V53이 `spot_id`를 지우므로, 구독자에 그 컬럼이
-- `NOT NULL`로 남아 있으면 복제된 INSERT가 값을 싣지 못해 거부되고 **복제가 조용히 멈춘다** —
-- 앱은 정상으로 보이는데 인기 순위만 이관 직전 상태로 얼어붙는다.
--
-- UNIQUE·FK도 함께 지운다. 구독자 제약이 발행자보다 엄격하면 같은 이유로 복제가 막힌다.
ALTER TABLE spot_reaction DROP CONSTRAINT IF EXISTS uq_spot_reaction;
ALTER TABLE spot_reaction DROP CONSTRAINT IF EXISTS fk_spot_reaction_spot;
DROP INDEX IF EXISTS idx_spot_reaction_spot_reaction;
ALTER TABLE spot_reaction DROP COLUMN spot_id;
