-- SPEC-0030 후속 · 검색 노드에도 `district_code` 자리를 만든다.
--
-- **이름과 타입은 메인 V75와 일치해야 한다** — 발행 측에 있는 컬럼이 구독 측에 없으면
-- 복제가 멈춘다. 실제로 멈춰 있었다: 워커가 `missing replicated column: "district_code"`로
-- 죽고 5초마다 재시작을 반복했고, 그동안 발행 측 슬롯이 WAL을 1.3GB까지 붙들었다.
--
-- **검색 노드는 이 값을 읽지 않는다.** 칸 상세가 쓰는 필터이고 그 질의는 메인이 처리한다.
-- 그래도 컬럼은 있어야 한다 — 복제는 쓰임이 아니라 형태를 맞춘다.
--
-- 같은 이유로 **메인 V75의 인덱스(idx_spot_catalog_district)는 만들지 않는다.** 인덱스는
-- 복제 대상이 아니고, 읽지 않는 컬럼에 색인을 두면 적용 비용만 늘어난다.
--
-- NULL을 허용한다. 어느 시군구에도 속하지 않는 좌표가 실제로 있고(메인 실측 43,216행 중
-- 273행), 값은 메인의 배치가 정해 복제로 따라온다.
ALTER TABLE tour.spot_catalog ADD COLUMN IF NOT EXISTS district_code varchar(5);
