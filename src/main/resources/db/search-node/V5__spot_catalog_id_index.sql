-- SPEC-0019 · 검색 노드의 `spot.catalog_id` 인덱스.
--
-- **검색 hot path에 있다.** 카드 조회(`SpotSearchJdbcAdapter.loadCards`)가
-- `EXISTS (SELECT 1 FROM spot WHERE catalog_id = cat.id)`로 원본이 사라진 카탈로그를 거르는데,
-- 인덱스가 없으면 결과 건수만큼 `spot`(약 12만 행) 순차 스캔이 반복된다.
--
-- 메인 DB의 `idx_spot_catalog_id`(V52)와 같은 정의다 — 부분 인덱스의 술어가
-- `catalog_id = <not null>`을 포함하므로 이 EXISTS가 인덱스를 탄다.
--
-- V3를 고치지 않고 새 파일로 두는 이유는 그 파일이 이미 적용돼 체크섬이 잡혀 있기 때문이다.
CREATE INDEX IF NOT EXISTS idx_spot_catalog_id ON spot (catalog_id) WHERE catalog_id IS NOT NULL;
