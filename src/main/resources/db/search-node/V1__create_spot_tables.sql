-- SPEC-0013 · 검색 노드의 spot 스키마
--
-- **이 경로는 검색 노드(ieuri-search) 전용이다.** 메인 DB는 db/migration이 소유하며,
-- 두 경로는 각자의 flyway_schema_history를 갖는다.
--
-- 논리 복제는 **행만 옮기고 테이블 구조는 옮기지 않는다.** 구독자에 그릇이 미리 있어야
-- 발행자의 행을 받을 수 있어서, 여기서 만든다.
--
-- 메인의 V11~V22가 점진적으로 만든 결과를 **최종 형태 하나로 압축했다.** 검색 노드는
-- 신규라 이력을 재현할 이유가 없다. 대응 관계는 아래 각 블록의 주석에 남긴다.
--
-- **컬럼 정의는 메인과 정확히 일치해야 한다.** 어긋나면 복제가 조용히 멈춘다 —
-- 앱은 정상 동작하는데 검색 결과만 낡아간다. spot 스키마를 바꿀 때 이 파일도 함께 고칠 것.

-- ── spot (메인 V13 + V15의 location) ────────────────────────────────────────
--
-- 언어별 행을 갖는다(UNIQUE(content_id, language)). BM25 인덱스를 언어별 부분 인덱스로
-- 나누는 근거이며, 조회가 language를 함께 걸어야 다른 언어가 섞이지 않는다.
CREATE TABLE spot (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content_id          VARCHAR(32)  NOT NULL,
    language            VARCHAR(2)   NOT NULL,
    title               VARCHAR(255) NOT NULL,
    address             VARCHAR(500),
    thumbnail_image_url VARCHAR(500) NOT NULL,
    map_x               DOUBLE PRECISION NOT NULL,
    map_y               DOUBLE PRECISION NOT NULL,
    category            VARCHAR(30)  NOT NULL,
    content_type_id     INTEGER      NOT NULL,
    copyright           VARCHAR(20)  NOT NULL,
    last_synced_at      TIMESTAMPTZ  NOT NULL,
    created_at          TIMESTAMPTZ  NOT NULL,
    updated_at          TIMESTAMPTZ  NOT NULL,
    -- PostGIS geography. 메인에서는 트리거가 map_x/map_y로부터 채우지만, 여기서는
    -- **복제로 값이 그대로 넘어오므로 트리거를 두지 않는다** — 두면 같은 값을 두 번 쓴다.
    location            geography(Point, 4326) NOT NULL,
    CONSTRAINT uq_spot UNIQUE (content_id, language),
    CONSTRAINT ck_spot_language CHECK (language IN ('EN', 'KO', 'JA', 'ZH')),
    CONSTRAINT ck_spot_map_x CHECK (map_x >= -180 AND map_x <= 180),
    CONSTRAINT ck_spot_map_y CHECK (map_y >= -90 AND map_y <= 90),
    CONSTRAINT ck_spot_thumbnail_not_blank CHECK (btrim(thumbnail_image_url) <> '')
);

-- 반경 필터·거리 정렬(R6·R17·R18). 검색 결과에도 거리가 필요하다.
CREATE INDEX idx_spot_location ON spot USING GIST (location);
-- 언어·카테고리 필터.
CREATE INDEX idx_spot_language_category ON spot (language, category);

-- ── spot_festival (메인 V18 + V19·V20의 재설계 반영) ────────────────────────
--
-- 진행 중 축제 조회(R17)가 spot과 조인한다. language 컬럼이 없어 spot을 통해 언어가 정해진다.
CREATE TABLE spot_festival (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    spot_id          BIGINT      NOT NULL,
    event_start_date DATE        NOT NULL,
    event_end_date   DATE        NOT NULL,
    progress_type    VARCHAR(50),
    festival_type    VARCHAR(50),
    last_synced_at   TIMESTAMPTZ NOT NULL,
    created_at       TIMESTAMPTZ NOT NULL,
    updated_at       TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_spot_festival UNIQUE (spot_id),
    CONSTRAINT ck_spot_festival_period CHECK (event_end_date >= event_start_date),
    CONSTRAINT fk_spot_festival_spot FOREIGN KEY (spot_id) REFERENCES spot(id) ON DELETE CASCADE
);

-- 종료일 필터(R17).
CREATE INDEX idx_spot_festival_end_date ON spot_festival (event_end_date);

-- ── spot_reaction (메인 V11 + V12·V20·V21) ──────────────────────────────────
--
-- 인기 조회(R18)가 LIKE를 spot 단위로 집계한다. member_id는 auth 도메인의 id지만
-- **물리 FK가 없다** — 도메인 간 FK 금지 규칙 그대로다.
CREATE TABLE spot_reaction (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id  BIGINT      NOT NULL,
    spot_id    BIGINT      NOT NULL,
    reaction   VARCHAR(10) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_spot_reaction UNIQUE (member_id, spot_id),
    CONSTRAINT ck_spot_reaction_reaction CHECK (reaction IN ('LIKE', 'DISLIKE')),
    CONSTRAINT fk_spot_reaction_spot FOREIGN KEY (spot_id) REFERENCES spot(id) ON DELETE CASCADE
);

-- 인기 집계(R18)가 타는 인덱스.
CREATE INDEX idx_spot_reaction_spot_reaction ON spot_reaction (spot_id, reaction);
