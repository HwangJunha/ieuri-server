package org.around.ieuri.community.domain.vo

/**
 * 피드 정렬 방식. **무엇이 보이는지까지 함께 정한다** — 정렬 기준이 다르면 담을 수 있는
 * 글의 범위도 달라지기 때문이다.
 */
enum class PostSortOrder {
    /**
     * 최신순. **장소 없는 글도 함께 나온다** — 좌표 반경으로 좁힌 경우에도 그렇다.
     *
     * 장소를 고르지 않고 쓴 글이 지역 피드에서 영원히 보이지 않는 것을 막는다.
     * 그런 글은 거리를 갖지 않아 거리순 목록에는 끼워 넣을 자리가 없지만, 최신순에는 있다.
     */
    LATEST,

    /**
     * 가까운 순. 반경 안 spot에 붙은 글만 나오며 **장소 없는 글은 빠진다** —
     * 거리가 없는 글을 거리순 목록의 어디에 둘지 정할 방법이 없다.
     *
     * 좌표를 주지 않으면 거리를 잴 기준이 없어 [LATEST]와 같게 동작한다.
     */
    DISTANCE,
}
